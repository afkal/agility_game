// The first week's doors. Each brings in one new thing and keeps every
// earlier obstacle in play, so the courses grow fuller day by day:
//
//   1  hurdles, gaps, gift-box tables, stairs and the A-frame
//   2  + snowballs
//   3  + snowmen
//   4  + spruce branches and cookies that need the second jump
//   5  + tunnels
//   6  Independence Day: everything so far, in blue and white
//   7  the week's finale: everything, closer together, snowballs in groups

import { Builder, type CourseLayout } from '../course.ts';

export function door1(): CourseLayout {
  const b = new Builder();
  b.flat(900, true);
  b.hurdle();
  b.flat(400, true);
  b.gap(100);
  b.flat(500, true);
  b.table(350, 70);
  b.flat(400, true);
  b.hurdle();
  b.flat(500, true);
  b.checkpoint();
  b.stairs(70, 140);
  b.flat(400, true);
  b.hurdle();
  b.flat(300, false);
  b.hurdle();
  b.flat(400, true);
  b.gap(110);
  b.flat(500, true);
  b.checkpoint();
  b.aframe();
  b.flat(400, true);
  b.table(400, 90);
  b.flat(300, false);
  b.gap(120);
  b.flat(400, true);
  b.hurdle();
  b.flat(500, true);
  b.checkpoint();
  b.stairs(80, 160);
  b.flat(300, false);
  b.hurdle();
  b.flat(400, true);
  b.gap(120);
  b.flat(400, true);
  b.aframe();
  b.flat(500, true);
  b.checkpoint();
  b.table(300, 100);
  b.flat(300, true);
  b.hurdle();
  b.flat(300, false);
  b.hurdle();
  b.flat(400, true);
  b.gap(130);
  // A last stretch without a flag.
  b.hurdle();
  b.flat(400, true);
  b.table(300, 80);
  b.flat(300, false);
  b.gap(110);
  b.flat(400, true);
  b.stairs(70, 150);
  b.flat(400, true);
  b.aframe();
  b.flat(600, true);
  b.finish();
  return b.build();
}

